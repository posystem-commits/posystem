export const makeSiteT = (lang) => (key, vars) => {
  const template = (SITE_STRINGS[lang] && SITE_STRINGS[lang][key]) || SITE_STRINGS.en[key] || key;
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ""));
};
